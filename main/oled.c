static esp_err_t oled_write_cmd(uint8_t cmd)
{
    i2c_cmd_handle_t cmd_i2c = i2c_cmd_link_create();
    i2c_master_start(cmd_i2c);
    i2c_master_write_byte(cmd_i2c, (OLED_ADDR << 1) | I2C_MASTER_WRITE, true);
    i2c_master_write_byte(cmd_i2c, OLED_CMD, true);
    i2c_master_write_byte(cmd_i2c, cmd, true);
    i2c_master_stop(cmd_i2c);
    esp_err_t ret = i2c_master_cmd_begin(I2C_MASTER_NUM, cmd_i2c, 1000 / portTICK_PERIOD_MS);
    i2c_cmd_link_delete(cmd_i2c);
    return ret;
}

static esp_err_t oled_write_data(uint8_t data)
{
    i2c_cmd_handle_t cmd = i2c_cmd_link_create();
    i2c_master_start(cmd);
    i2c_master_write_byte(cmd, (OLED_ADDR << 1) | I2C_MASTER_WRITE, true);
    i2c_master_write_byte(cmd, OLED_DATA, true);
    i2c_master_write_byte(cmd, data, true);
    i2c_master_stop(cmd);
    esp_err_t ret = i2c_master_cmd_begin(I2C_MASTER_NUM, cmd, 1000 / portTICK_PERIOD_MS);
    i2c_cmd_link_delete(cmd);
    return ret;
}

void oled_init(void)
{
    vTaskDelay(pdMS_TO_TICKS(100));
    
    oled_write_cmd(0xAE);
    oled_write_cmd(0xD5);
    oled_write_cmd(0x80);
    oled_write_cmd(0xA8);
    oled_write_cmd(0x3F);
    oled_write_cmd(0xD3);
    oled_write_cmd(0x00);
    oled_write_cmd(0x40);
    oled_write_cmd(0x8D);
    oled_write_cmd(0x14);
    oled_write_cmd(0x20);
    oled_write_cmd(0x02);
    oled_write_cmd(0xA1);
    oled_write_cmd(0xC8);
    oled_write_cmd(0xDA);
    oled_write_cmd(0x12);
    oled_write_cmd(0x81);
    oled_write_cmd(0xCF);
    oled_write_cmd(0xD9);
    oled_write_cmd(0xF1);
    oled_write_cmd(0xDB);
    oled_write_cmd(0x30);
    oled_write_cmd(0xA4);
    oled_write_cmd(0xA6);
    oled_clear();
    oled_write_cmd(0xAF);
    
    ESP_LOGI(TAG, "OLED initialized");
}

void oled_clear(void)
{
    memset(oled_buffer, 0, sizeof(oled_buffer));
    oled_refresh();
}

void oled_clear_line(uint8_t page)
{
    if (page >= OLED_PAGES) return;
    memset(oled_buffer[page], 0, OLED_WIDTH);
}

void oled_display_on(void)
{
    oled_write_cmd(0x8D);
    oled_write_cmd(0x14);
    oled_write_cmd(0xAF);
}

void oled_display_off(void)
{
    oled_write_cmd(0x8D);
    oled_write_cmd(0x10);
    oled_write_cmd(0xAE);
}

void oled_set_pos(uint8_t page, uint8_t col)
{
    oled_write_cmd(0xB0 | page);
    oled_write_cmd(0x10 | ((col & 0xF0) >> 4));
    oled_write_cmd(0x00 | (col & 0x0F));
}

void oled_write_char(uint8_t page, uint8_t col, char c)
{
    if (page >= OLED_PAGES || col + 6 > OLED_WIDTH) return;
    
    uint8_t idx = c - 32;
    if (idx > 94) idx = 0;
    
    for (uint8_t i = 0; i < 6; i++) {
        oled_buffer[page][col + i] = font6x8[idx][i];
    }
}

void oled_write_string(uint8_t page, uint8_t col, const char *str)
{
    if (page >= OLED_PAGES) return;
    
    while (*str && col + 6 <= OLED_WIDTH) {
        oled_write_char(page, col, *str);
        col += 6;
        str++;
    }
}

void oled_write_num(uint8_t page, uint8_t col, int32_t num, uint8_t len)
{
    char buf[12];
    char fmt[8];
    snprintf(fmt, sizeof(fmt), "%%%dd", len);
    snprintf(buf, sizeof(buf), fmt, num);
    oled_write_string(page, col, buf);
}

void oled_draw_bmp(uint8_t page, uint8_t col, const uint8_t *bmp, uint8_t width, uint8_t height)
{
    uint8_t pages_needed = (height + 7) / 8;
    for (uint8_t p = 0; p < pages_needed && page + p < OLED_PAGES; p++) {
        for (uint8_t x = 0; x < width && col + x < OLED_WIDTH; x++) {
            oled_buffer[page + p][col + x] = bmp[p * width + x];
        }
    }
}

void oled_refresh(void)
{
    for (uint8_t page = 0; page < OLED_PAGES; page++) {
        oled_set_pos(page, 0);
        for (uint8_t col = 0; col < OLED_WIDTH; col++) {
            oled_write_data(oled_buffer[page][col]);
        }
    }
}
